describe("isReadOnlyAction", () => {
  it.each(READ_ONLY)("hides read-only action %s", (a) => {
    expect(isReadOnlyAction(a)).toBe(true);
  });

  it.each(VISIBLE)("keeps %s visible", (a) => {
    expect(isReadOnlyAction(a)).toBe(false);
  });

  it("hides the reported leaks", () => {
    for (const a of [
      "authz.check",
      "dashboard.summary",
      "discovery.summary",
      "report.ca_health",
      "report.expiry_timeline",
    ]) {
      expect(isReadOnlyAction(a)).toBe(true);
    }
  });

  it("never hides exports, downloads or evidence packs", () => {
    for (const a of [
      "report.export",
      "key.export",
      "byok.export",
      "cbom.export",
      "certificate.download",
      "report.compliance_evidence",
      "report.compliance_evidence_pdf",
      "report.executive_summary_pdf",
    ]) {
      expect(isReadOnlyAction(a)).toBe(false);
    }
  });
});
