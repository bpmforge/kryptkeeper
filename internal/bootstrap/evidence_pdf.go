// orgName returns the organization name printed on evidence packs.
func orgName() string {
	if v := strings.TrimSpace(os.Getenv("KRYPTKEEPER_ORG_NAME")); v != "" {
		return v
	}
	return "Kryptkeeper"
}

// frameworkDisplayName maps a framework key to its audit-facing title.
func frameworkDisplayName(framework string) string {
	switch strings.ToLower(framework) {
	case "pci":
		return "PCI DSS 4.0.1"
	case "soc2":
		return "SOC 2"
	case "nist":
		return "NIST SP 800-57"
	case "dora":
		return "EU DORA"
	case "nis2":
		return "EU NIS2"
	case "fedramp":
		return "FedRAMP Moderate (mapping)"
	case "", "all":
		return "All Frameworks"
	default:
		return strings.ToUpper(framework)
	}
}

// status colors (RGB) for evidence pack badges.
var statusRGB = map[string][3]int{
	"pass": {34, 197, 94},
	"warn": {245, 158, 11},
	"fail": {239, 68, 68},
}

// pdfCompression is false only in tests that read text back out of the PDF
// bytes (fpdf compresses page streams by default).
var pdfCompression = true

// newBrandedPDF returns an A4 PDF with a consistent header/footer. createdAt is
// passed in (never time.Now inside) and pins both PDF timestamps so the only
// source of byte variation is fpdf's internal random font tag — the rendered
// content is otherwise a pure function of the input.
func newBrandedPDF(title string, createdAt time.Time) (*fpdf.Fpdf, func(string) string) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetCompression(pdfCompression)
	// Pin both dates so rendered bytes are deterministic for a fixed createdAt
	// (ModDate otherwise defaults to time.Now()).
	pdf.SetCreationDate(createdAt.UTC())
	pdf.SetModificationDate(createdAt.UTC())
	pdf.AliasNbPages("")
	tr := pdf.UnicodeTranslatorFromDescriptor("")

	org := orgName()
	stamp := createdAt.UTC().Format("2006-01-02 15:04 MST")

	pdf.SetHeaderFunc(func() {
		pdf.SetFont("Helvetica", "B", 9)
		pdf.SetTextColor(100, 116, 139)
		pdf.CellFormat(0, 6, tr(org), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 6, tr("Generated "+stamp), "", 1, "R", false, 0, "")
		pdf.SetDrawColor(203, 213, 225)
		pdf.Line(10, 18, 200, 18)
		pdf.Ln(6)
	})
	pdf.SetFooterFunc(func() {
		pdf.SetY(-15)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(148, 163, 184)
		pdf.CellFormat(0, 8, tr("CONFIDENTIAL — generated by Kryptkeeper"), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 8, fmt.Sprintf("Page %d of {nb}", pdf.PageNo()), "", 0, "R", false, 0, "")
	})
	_ = title
	return pdf, tr
}

// renderComplianceEvidencePDF renders a compliance evidence pack as a branded
// PDF. certCount is the size of the inventory the evidence was drawn from.
func renderComplianceEvidencePDF(report ComplianceEvidenceReport, certCount int, createdAt time.Time) ([]byte, error) {
	fw := frameworkDisplayName(report.Framework)
	pdf, tr := newBrandedPDF("Compliance Evidence", createdAt)
	pdf.AddPage()

	// Cover / title block.
	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 20)
	pdf.CellFormat(0, 12, tr(fw+" — Compliance Evidence Pack"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 11)
	pdf.SetTextColor(71, 85, 105)
	pdf.CellFormat(0, 7, tr(fmt.Sprintf("%s · %d certificates in scope", orgName(), certCount)), "", 1, "L", false, 0, "")
	pdf.Ln(4)

	// Summary band.
	s := report.Summary
	total := s.Pass + s.Warn + s.Fail
	pct := 0
	if total > 0 {
		pct = s.Pass * 100 / total
	}
	pdf.SetFont("Helvetica", "B", 12)
	pdf.SetTextColor(15, 23, 42)
	pdf.CellFormat(0, 8, tr(fmt.Sprintf("Control summary: %d pass · %d warn · %d fail  (%d%% passing)", s.Pass, s.Warn, s.Fail, pct)), "", 1, "L", false, 0, "")
	pdf.Ln(2)
	if frameworkIncludesFedramp(report.Framework) {
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(100, 116, 139)
		pdf.MultiCell(0, 4, tr(fedrampMappingNotice), "", "L", false)
		pdf.Ln(2)
	}

	// One block per control.
	for _, c := range report.Controls {
		status := strings.ToLower(c.Status)
		rgb, ok := statusRGB[status]
		if !ok {
			rgb = [3]int{148, 163, 184}
		}

		// Status badge + control id/title row.
		pdf.SetFont("Helvetica", "B", 9)
		pdf.SetFillColor(rgb[0], rgb[1], rgb[2])
		pdf.SetTextColor(255, 255, 255)
		pdf.CellFormat(22, 7, tr(strings.ToUpper(status)), "", 0, "C", true, 0, "")
		pdf.SetTextColor(15, 23, 42)
		pdf.SetFont("Helvetica", "B", 10)
		title := c.ID
		if c.Title != "" {
			title += " — " + c.Title
		}
		pdf.CellFormat(0, 7, tr(" "+title), "", 1, "L", false, 0, "")

		// Evidence + remediation.
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(51, 65, 85)
		if c.Evidence != "" {
			pdf.MultiCell(0, 5, tr("Evidence: "+c.Evidence), "", "L", false)
		}
		if c.Remediation != "" {
			pdf.SetTextColor(180, 83, 9)
			pdf.MultiCell(0, 5, tr("Remediation: "+c.Remediation), "", "L", false)
		}
		pdf.SetFont("Helvetica", "", 8)
		pdf.SetTextColor(100, 116, 139)
		if c.Rule != "" {
			pdf.MultiCell(0, 4, tr("Rule: "+c.Rule), "", "L", false)
		}
		if len(c.Artifacts) > 0 {
			parts := make([]string, 0, len(c.Artifacts))
			for _, a := range c.Artifacts {
				parts = append(parts, fmt.Sprintf("%s (%s)", a.Kind, a.URL))
			}
			pdf.MultiCell(0, 4, tr("Artifacts: "+strings.Join(parts, "; ")), "", "L", false)
		}
		pdf.Ln(2)
	}

	renderAcceptedRisksSection(pdf, tr, report.AcceptedRisks)
	renderKeyCustodySection(pdf, tr, report.KeyCustody, report.KeyCustodyNote)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	if err := pdf.Error(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// renderAcceptedRisksSection is always present so an auditor can see "none"
// as well as what was excused.
func renderAcceptedRisksSection(pdf *fpdf.Fpdf, tr func(string) string, risks []AcceptedRisk) {
	pdf.Ln(4)
	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 13)
	pdf.CellFormat(0, 9, tr(fmt.Sprintf("Accepted risks (%d)", len(risks))), "", 1, "L", false, 0, "")
	if len(risks) == 0 {
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(51, 65, 85)
		pdf.MultiCell(0, 5, tr("No accepted risks are active."), "", "L", false)
		return
	}
	for _, r := range risks {
		pdf.SetFont("Helvetica", "B", 10)
		pdf.SetTextColor(15, 23, 42)
		pdf.MultiCell(0, 6, tr(fmt.Sprintf("%s — %s %s", r.FindingCode, r.TargetType, r.TargetID)), "", "L", false)
		owner := r.OwnerTeam
		if owner == "" {
			owner = "unowned"
		}
		if r.OwnerEmail != "" {
			owner += " " + r.OwnerEmail
		}
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(51, 65, 85)
		pdf.MultiCell(0, 5, tr(fmt.Sprintf("Owner: %s · Justification: %s · Expires: %s · Approved/created by: %s",
			owner, r.JustificationCode, r.ExpiresAt, r.CreatedBy)), "", "L", false)
		if r.JustificationNote != "" {
			pdf.MultiCell(0, 5, tr("Note: "+r.JustificationNote), "", "L", false)
		}
		pdf.Ln(2)
	}
}

// maxCustodyPDFRows caps the key table so a very large keystore cannot blow
// up the pack; the full list is in the custody_report artifact.
const maxCustodyPDFRows = 100

// renderKeyCustodySection is always present: a nil report prints why.
func renderKeyCustodySection(pdf *fpdf.Fpdf, tr func(string) string, kc *KeyCustodyReport, note string) {
	pdf.Ln(4)
	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 13)
	pdf.CellFormat(0, 9, tr("Key custody"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(51, 65, 85)
	if kc == nil {
		if note == "" {
			note = "key custody evidence is unavailable"
		}
		pdf.MultiCell(0, 5, tr("Key custody evidence not included: "+note), "", "L", false)
		return
	}
	escrow := "no"
	if kc.DualControlEscrow {
		escrow = "yes"
	}
	pdf.MultiCell(0, 5, tr(fmt.Sprintf("Backend: %s | Dual-control escrow: %s | Keys: %d", kc.Backend, escrow, len(kc.Keys))), "", "L", false)
	pdf.SetFont("Helvetica", "", 8)
	shown := kc.Keys
	if len(shown) > maxCustodyPDFRows {
		shown = shown[:maxCustodyPDFRows]
	}
	for _, k := range shown {
		last := k.LastRotatedAt
		if last == "" {
			last = "never"
		}
		pdf.MultiCell(0, 4, tr(fmt.Sprintf("%s | %s | %s | %d | %s | %d",
			k.KeyID, k.Algorithm, k.CreatedAt, k.RotationCount, last, k.AccessCount)), "", "L", false)
	}
	if more := len(kc.Keys) - len(shown); more > 0 {
		pdf.MultiCell(0, 4, tr(fmt.Sprintf("... and %d more", more)), "", "L", false)
	}
}

// metricTone returns an RGB color for a 0-100 metric (green/amber/red).
func metricTone(pct, warnAt, goodAt int) [3]int {
	switch {
	case pct >= goodAt:
		return statusRGB["pass"]
	case pct >= warnAt:
		return statusRGB["warn"]
	default:
		return statusRGB["fail"]
	}
}

// renderExecutiveSummaryPDF renders the one-page, board-readable summary.
func renderExecutiveSummaryPDF(s ExecutiveSummary, createdAt time.Time) ([]byte, error) {
	pdf, tr := newBrandedPDF("Executive Summary", createdAt)
	pdf.AddPage()

	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 22)
	pdf.CellFormat(0, 13, tr("Certificate Posture — Executive Summary"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 11)
	pdf.SetTextColor(71, 85, 105)
	pdf.CellFormat(0, 7, tr(fmt.Sprintf("%s · %d certificates", s.Org, s.TotalCerts)), "", 1, "L", false, 0, "")
	pdf.Ln(4)

	// Headline metric tiles (2x2): PQC, automation, compliance, expiry risk.
	tiles := []struct {
		label string
		value string
		rgb   [3]int
	}{
		// Both numbers, or "ready to migrate" reads as "done": an all-ECDSA
		// estate scores 100% on PQCScorePercent (it counts migration_ready)
		// while holding zero post-quantum keys. Tone follows the honest one.
		{"Post-Quantum", fmt.Sprintf("%d%% safe · %d%% ready", s.QuantumSafePercent, s.PQCScorePercent), metricTone(s.QuantumSafePercent, 40, 80)},
		{"Renewal Automation", fmt.Sprintf("%d%%", s.AutomationPercent), metricTone(s.AutomationPercent, 40, 80)},
		{"Compliance Pass Rate", fmt.Sprintf("%d%%", s.CompliancePassPercent), metricTone(s.CompliancePassPercent, 70, 95)},
		{"Expiring <=47 days", fmt.Sprintf("%d", s.Expired+s.Expiring47d), expiryTone(s.Expired + s.Expiring47d)},
	}
	const tw, th = 92.0, 26.0
	x0, y0 := 10.0, pdf.GetY()
	for i, t := range tiles {
		col := float64(i % 2)
		row := float64(i / 2)
		x := x0 + col*(tw+6)
		y := y0 + row*(th+6)
		pdf.SetXY(x, y)
		pdf.SetFillColor(t.rgb[0], t.rgb[1], t.rgb[2])
		pdf.SetTextColor(255, 255, 255)
		pdf.SetFont("Helvetica", "B", 22)
		pdf.CellFormat(tw, th, tr(t.value), "", 0, "C", true, 0, "")
		// Label under the value.
		pdf.SetXY(x, y+th-7)
		pdf.SetFont("Helvetica", "B", 8)
		pdf.CellFormat(tw, 6, tr(strings.ToUpper(t.label)), "", 0, "C", false, 0, "")
	}
	pdf.SetXY(x0, y0+2*(th+6)+2)

	// Compliance band.
	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.CellFormat(0, 8, tr(fmt.Sprintf("Compliance: %d pass · %d warn · %d fail",
		s.Compliance.Pass, s.Compliance.Warn, s.Compliance.Fail)), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(71, 85, 105)
	pdf.CellFormat(0, 6, tr(fmt.Sprintf("Risk: %d critical · %d high", s.RiskCritical, s.RiskHigh)), "", 1, "L", false, 0, "")
	// Nil for tenant-scoped callers (keys are hub-wide), so the line is omitted
	// rather than printed as zeros; counts are the PQC posture page's own.
	if k := s.KeyPQC; k != nil {
		pdf.CellFormat(0, 6, tr(fmt.Sprintf("Keys ready / not ready / unknown for PQC migration: %d / %d / %d", k.Ready, k.NotReady, k.Unknown)), "", 1, "L", false, 0, "")
	}
	if pc := s.PrivilegedCredentials; pc != nil {
		pdf.CellFormat(0, 6, tr(fmt.Sprintf("Privileged credentials: %d in use on %d hosts", pc.Count, pc.HostCount)), "", 1, "L", false, 0, "")
	}
	pdf.Ln(3)

	// Top risks.
	pdf.SetFont("Helvetica", "B", 12)
	pdf.SetTextColor(15, 23, 42)
	pdf.CellFormat(0, 8, tr("Top Risks & Actions"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(51, 65, 85)
	for _, risk := range s.TopRisks {
		pdf.MultiCell(0, 6, tr("-  "+risk), "", "L", false)
	}
	renderExecutiveTrendSection(pdf, tr, s.Trend)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	if err := pdf.Error(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// renderExecutiveTrendSection appends the "Posture trend" section: an
// explicit message for a nil (tenant-scoped) or empty trend, else a table of
// the most recent 12 snapshots, newest last.
func renderExecutiveTrendSection(pdf *fpdf.Fpdf, tr func(string) string, t *ExecutiveTrend) {
	pdf.Ln(3)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.SetTextColor(15, 23, 42)
	pdf.CellFormat(0, 8, tr("Posture trend (last 90 days)"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(51, 65, 85)
	switch {
	case t == nil:
		pdf.MultiCell(0, 6, tr("Posture trend is available to fleet administrators only."), "", "L", false)
		return
	case len(t.Points) == 0:
		pdf.MultiCell(0, 6, tr("No posture snapshots in the last 90 days."), "", "L", false)
		return
	}
	const maxRows = 12
	pts := t.Points
	if len(pts) > maxRows {
		pts = pts[len(pts)-maxRows:]
	}
	cols := []string{"A", "B", "C", "D", "F"}
	pdf.SetFont("Helvetica", "B", 9)
	pdf.CellFormat(34, 6, "Date", "B", 0, "L", false, 0, "")
	pdf.CellFormat(24, 6, "Certs", "B", 0, "R", false, 0, "")
	for _, g := range cols {
		pdf.CellFormat(18, 6, g, "B", 0, "R", false, 0, "")
	}
	pdf.Ln(-1)
	pdf.SetFont("Helvetica", "", 9)
	for _, p := range pts {
		d := p.CapturedAt
		if len(d) > 10 {
			d = d[:10]
		}
		pdf.CellFormat(34, 5, tr(d), "", 0, "L", false, 0, "")
		pdf.CellFormat(24, 5, fmt.Sprintf("%d", p.TotalCerts), "", 0, "R", false, 0, "")
		for _, g := range cols {
			pdf.CellFormat(18, 5, fmt.Sprintf("%d", p.Grades[g]), "", 0, "R", false, 0, "")
		}
		pdf.Ln(-1)
	}
	if len(t.Points) > maxRows {
		pdf.SetFont("Helvetica", "", 8)
		pdf.CellFormat(0, 5, tr(fmt.Sprintf("Showing %d of %d snapshots.", maxRows, len(t.Points))), "", 1, "L", false, 0, "")
	}
}

// expiryTone colors the expiry-risk tile: 0 is good, any expiring is bad.
func expiryTone(n int) [3]int {
	if n == 0 {
		return statusRGB["pass"]
	}
	return statusRGB["fail"]
}

// pqcStatusRGB colors the countdown status banner.
func pqcStatusRGB(status string) [3]int {
	switch status {
	case "complete", "on_track":
		return statusRGB["pass"]
	case "at_risk":
		return statusRGB["warn"]
	default:
		return statusRGB["fail"]
	}
}

// renderPQCCountdownPDF renders the PQC migration "proof of progress" one-pager:
// readiness, deadline countdowns, per-wave progress, and the trend.
func renderPQCCountdownPDF(rep PQCCountdownReport, createdAt time.Time) ([]byte, error) {
	pdf, tr := newBrandedPDF("PQC Migration Countdown", createdAt)
	pdf.AddPage()

	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 20)
	pdf.CellFormat(0, 12, tr("Post-Quantum Migration — Countdown & Proof"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 11)
	pdf.SetTextColor(71, 85, 105)
	pdf.CellFormat(0, 7, tr(fmt.Sprintf("%s · %d certificates · %d%% PQC-ready",
		rep.Org, rep.TotalCerts, rep.PQCScorePercent)), "", 1, "L", false, 0, "")
	pdf.Ln(2)

	// Status banner.
	rgb := pqcStatusRGB(rep.Status)
	pdf.SetFillColor(rgb[0], rgb[1], rgb[2])
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.CellFormat(0, 9, tr("Status: "+strings.ToUpper(strings.ReplaceAll(rep.Status, "_", " "))), "", 1, "C", true, 0, "")
	pdf.Ln(3)

	// Readiness counts.
	pdf.SetTextColor(15, 23, 42)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.CellFormat(0, 8, tr(fmt.Sprintf("Quantum-safe: %d   Migration-ready: %d   Vulnerable: %d",
		rep.QuantumSafe, rep.MigrationReady, rep.Vulnerable)), "", 1, "L", false, 0, "")
	pdf.Ln(2)

	// Deadlines.
	pdf.SetFont("Helvetica", "B", 12)
	pdf.CellFormat(0, 8, tr("Regulatory deadlines"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(51, 65, 85)
	for _, d := range rep.Deadlines {
		line := fmt.Sprintf("%s — %s", d.Date, d.Name)
		if d.Passed {
			line += "  (PASSED)"
		} else {
			line += fmt.Sprintf("  (%d days remaining)", d.DaysRemaining)
		}
		pdf.MultiCell(0, 5, tr("-  "+line), "", "L", false)
	}
	pdf.Ln(2)

	// Per-wave progress.
	if len(rep.Waves) > 0 {
		pdf.SetFont("Helvetica", "B", 12)
		pdf.SetTextColor(15, 23, 42)
		pdf.CellFormat(0, 8, tr("Migration waves"), "", 1, "L", false, 0, "")
		pdf.SetFont("Helvetica", "", 10)
		pdf.SetTextColor(51, 65, 85)
		for _, wv := range rep.Waves {
			owner := ""
			if wv.Owner != "" {
				owner = " [" + wv.Owner + "]"
			}
			pdf.MultiCell(0, 5, tr(fmt.Sprintf("-  %s%s — %d/%d migrated (%d%%)",
				wv.Name, owner, wv.Migrated, wv.Total, wv.ProgressPercent)), "", "L", false)
		}
		pdf.Ln(2)
	}

	// Trend summary (first vs latest snapshot).
	if len(rep.Trend) >= 2 {
		first := rep.Trend[0]
		last := rep.Trend[len(rep.Trend)-1]
		pdf.SetFont("Helvetica", "B", 12)
		pdf.SetTextColor(15, 23, 42)
		pdf.CellFormat(0, 8, tr("Trend"), "", 1, "L", false, 0, "")
		pdf.SetFont("Helvetica", "", 10)
		pdf.SetTextColor(51, 65, 85)
		pdf.MultiCell(0, 5, tr(fmt.Sprintf("PQC readiness moved from %d%% (%s) to %d%% (%s) over %d snapshots.",
			first.PQCScorePercent, dayKey(first.CapturedAt), last.PQCScorePercent, dayKey(last.CapturedAt), len(rep.Trend))), "", "L", false)
	}

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	if err := pdf.Error(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
